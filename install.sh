#!/usr/bin/env bash
# Idempotent setup: venv, pinned dependency, config skeleton, systemd user unit.
# Safe to re-run after a `git pull`. It never overwrites an existing config.
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
python=${PYTHON:-python3}
config_dir=~/.config/ratatoskr
unit_dir=~/.config/systemd/user

# Python 3.11+ is required (tomllib).
if ! "$python" -c 'import sys; sys.exit(sys.version_info < (3, 11))'; then
  echo "!! $python is older than 3.11; set PYTHON=/path/to/python3.11+" >&2
  exit 1
fi
command -v herdr >/dev/null || echo "!! herdr is not on PATH; the bot needs it at runtime" >&2

[[ -d $here/.venv ]] || "$python" -m venv "$here/.venv"
"$here/.venv/bin/pip" -q install -r "$here/requirements.txt"

mkdir -p "$config_dir"
if [[ ! -f $config_dir/config.toml ]]; then
  cp "$here/config.example.toml" "$config_dir/config.toml"
  echo ">> fill in token, guild_id and owner_id in $config_dir/config.toml"
fi
# The file holds the bot token: owner-only.
chmod 600 "$config_dir/config.toml"

# Render the unit with this checkout's path. A path under $HOME is written as
# %h/..., so the default ~/Work/ratatoskr renders to the template unchanged.
case $here in
  "$HOME"/*) unit_path="%h${here#"$HOME"}" ;;
  *)         unit_path=$here ;;
esac
if [[ $unit_path == *[[:space:]]* ]]; then
  echo "!! the checkout path contains whitespace; move it somewhere without spaces" >&2
  exit 1
fi
mkdir -p "$unit_dir"
# Older versions installed a symlink to the template; remove it first so the
# rendered unit does not overwrite the template through the link.
rm -f "$unit_dir/ratatoskr.service"
{
  echo "# Generated by $here/install.sh from ratatoskr.service. Edit that file, not this one."
  sed "s|%h/Work/ratatoskr|$unit_path|g" "$here/ratatoskr.service"
} > "$unit_dir/ratatoskr.service"
systemctl --user daemon-reload
echo ">> start with: systemctl --user enable --now ratatoskr"
echo ">> after an update: systemctl --user restart ratatoskr"
